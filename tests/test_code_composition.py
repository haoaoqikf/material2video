"""Tailwind source 索引只扫当前作品：完整类名进构建 CSS。

作品代码场景可以自由使用 Tailwind 类名，但只有**静态可发现**的完整类名
会被生成：直接写在 `className` 里的与完整字符串映射里的都算，运行时拼接的
不算。这条判据必须由真实构建产物验证——读源码或读配置都证明不了 CSS 里
真的有那条规则。

契约页只构建一次：作品目录与分镜是运行时数据，同一个 bundle 服务全部用例。
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

import m2v.engine.scene_manifest as scene_manifest

WEB_DIR = Path(__file__).resolve().parents[1] / "web"

# 代码场景模块：只用 @m2v/scene 的探针属性与共享令牌（CSS 变量取字体与强调色）。
# Tailwind 类名必须是完整字符串：直接写在 className 里的（rounded-xl、p-4）
# 与完整字符串映射里的（cls.box = 'gap-6 border-2'）都会被 @source 扫描进
# 构建 CSS；运行时拼接的类名不保证生成（见 web/README.md）。
GAUGE_MODULE = """import { probe, type M2VCodeScene } from '@m2v/scene';

const cls = { box: 'gap-6 border-2' };

const Gauge: M2VCodeScene<{ text: string }> = ({ scene, progress }) => {
  return (
    <div
      className={`rounded-xl p-4 ${cls.box}`}
      style={{ fontFamily: 'var(--m2v-font)', color: 'var(--m2v-accent)', padding: 40 }}
      {...probe({ node: 'gauge-value', role: 'headline' })}
    >
      {scene.data.text} · {Math.round(progress * 100)}%
    </div>
  );
};

export default Gauge;
"""


def _plan(modules: list[str]) -> dict:
    """通用视频材料：幕级 renderer 声明代码场景。"""
    scenes = [
        {
            "id": f"s{index}",
            "type": "code",
            "duration": {"frames": 30},
            "data": {"text": f"第{index}幕"},
            "renderer": {"kind": "code", "module": module},
        }
        for index, module in enumerate(modules)
    ]
    return {"schemaVersion": 1, "fps": 30, "width": 1080, "height": 1920, "scenes": scenes}


def _build_contract_page() -> None:
    completed = subprocess.run(
        [shutil.which("pnpm") or "pnpm", "build"], cwd=WEB_DIR, capture_output=True, text=True, encoding="utf-8", errors="replace"
    )
    assert completed.returncode == 0, completed.stdout + completed.stderr


@pytest.fixture(scope="module")
def built_env(tmp_path_factory):
    """一次性搭好带代码场景的作品、生成清单并构建契约页。"""
    root = tmp_path_factory.mktemp("content")
    article = root / "videos" / "mixed"
    (article / "scenes").mkdir(parents=True)
    (article / "assets").mkdir(exist_ok=True)
    (article / "scenes" / "gauge.tsx").write_text(GAUGE_MODULE, encoding="utf-8")
    (article / "assets" / "mark.svg").write_text(
        "<svg xmlns='http://www.w3.org/2000/svg'/>", encoding="utf-8"
    )
    storyboard_path = article / "general-plan.json"
    storyboard_path.write_text(json.dumps(_plan(["gauge"]), ensure_ascii=False), encoding="utf-8")
    scene_manifest.generate(web_dir=WEB_DIR, storyboard_path=storyboard_path, content_root=root)
    _build_contract_page()
    return root, article


