/**
 * 当前作品代码场景的静态清单生成器。
 *
 * Python 侧解析作品归属、校验模块之后，把允许的场景入口写成
 * `scene-manifest.json` 传给本脚本；本脚本在 `web/.gen/active-scenes.ts`
 * 写入**静态 import** 与模块映射。产物整体覆盖——切换作品时上一个作品
 * 的模块引用不会残留，失败或中断后下次运行也会重写而不是复用未知状态。
 *
 * 为什么要静态 import：Vite 与 Remotion webpack 都能按文件相对路径解析
 * 仓库外内容根的模块，TypeScript 也能；运行时动态 import 无法静态分析，
 * 也就进不了依赖白名单与源码指纹。路径转义在这里统一处理：
 * `path.relative` 计算相对位置，统一转成 POSIX 分隔符并去掉扩展名
 * （由解析器补全），Windows 反斜杠与盘符不会进入 import 字符串。
 *
 * 用法：
 * ```
 * node scripts/gen-active-scenes.mjs --manifest .gen/scene-manifest.json
 * ```
 * manifest 结构：{ webDir, outFile, modules: [{ id, module }] }
 * （module 为绝对路径，由 Python 侧解析归属后给出）
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) {
      throw new Error(`无法识别的参数: ${token}`);
    }
    const value = argv[i + 1];
    if (value === undefined || value.startsWith('--')) {
      throw new Error(`参数 ${token} 缺少取值`);
    }
    parsed[token.slice(2)] = value;
    i += 1;
  }
  return parsed;
}

/** 绝对模块路径 → 从生成文件出发可解析的 import 描述符。 */
function importSpecifier(fromDir, modulePath) {
  const relative = path
    .relative(fromDir, modulePath)
    .split(path.sep)
    .join('/');
  if (!relative || relative === '.') {
    throw new Error(`模块路径与生成目录重合：${modulePath}`);
  }
  const withPrefix = relative.startsWith('.') ? relative : `./${relative}`;
  return withPrefix.replace(/\.(tsx|ts|jsx|js|mjs)$/i, '');
}

const args = parseArgs(process.argv.slice(2));
if (!args.manifest) {
  process.stderr.write('gen-active-scenes: 需要 --manifest <scene-manifest.json>\n');
  process.exit(2);
}

const manifest = JSON.parse(fs.readFileSync(args.manifest, 'utf8'));
if (!Array.isArray(manifest.modules)) {
  throw new Error('scene-manifest 缺少 modules 数组');
}

const outFile = path.resolve(manifest.webDir, manifest.outFile ?? '.gen/active-scenes.ts');
const outDir = path.dirname(outFile);

// Tailwind source 索引：只把**当前作品**的 scenes/ 与 assets/ 交给扫描，
// 其他作品的文件不会被扫进来（历史内容不会意外进入成片，构建也更快）。
// 完整类名与完整字符串映射能被静态发现；运行时拼接的类名不保证生成，
// 这条限制记录在 web/README.md 与 skill 参考文档里。
const tailwindFile = path.resolve(manifest.webDir, '.gen/active-tailwind.css');
const tailwindLines = ['/* Generated by article2video; do not edit. */'];
if (manifest.articleDir && manifest.modules.length > 0) {
  for (const subdir of ['scenes', 'assets']) {
    const target = path.join(manifest.articleDir, subdir);
    if (fs.existsSync(target)) {
      const relative = path.relative(outDir, target).split(path.sep).join('/');
      tailwindLines.push(`@source "${relative}";`);
    }
  }
}
fs.mkdirSync(path.dirname(tailwindFile), { recursive: true });
fs.writeFileSync(tailwindFile, tailwindLines.join('\n') + '\n', 'utf8');

const header = [
  '// Generated by article2video; do not edit.',
  '// 当前作品的代码场景静态清单：preview / review / render 每次运行前整体覆盖，',
  '// 切换作品不会残留上一个作品的模块引用。',
  "import type { A2VCodeScene } from '@/code-scene';",
];

const imports = [];
const entries = [];
manifest.modules.forEach((entry, index) => {
  if (!entry?.id || !entry?.module) {
    throw new Error(`scene-manifest 第 ${index} 项缺少 id 或 module`);
  }
  const specifier = importSpecifier(outDir, entry.module);
  imports.push(`import s${index} from '${specifier}';`);
  entries.push(`  '${entry.id}': s${index},`);
});

const body = [''];
// 模块以 `A2VCodeScene<any>` 收录：各场景声明的 data 泛型互不相同，
// 包装器在运行时把幕数据原样交给组件，不在清单层做类型收窄。
if (manifest.modules.length === 0) {
  body.push('export const ACTIVE_CODE_SCENES: Record<string, A2VCodeScene<any>> = {};');
} else {
  body.push('export const ACTIVE_CODE_SCENES: Record<string, A2VCodeScene<any>> = {', ...entries, '};');
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, [...header, ...imports, ...body].join('\n') + '\n', 'utf8');
process.stdout.write(`gen-active-scenes: ${manifest.modules.length} 个代码场景 → ${outFile}\n`);
